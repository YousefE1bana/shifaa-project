// SAFE probe only: replace all network/process boundaries before loading the
// actual E2E files. The provider deliberately denies before adapter imports or
// fixture effects. This is not a real E2E run or an acceptance claim.
import assert from 'node:assert/strict';
import { run } from 'node:test';
import net from 'node:net';
import tls from 'node:tls';
import child from 'node:child_process';
import { syncBuiltinESMExports, registerHooks } from 'node:module';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { withTestLauncherSession } from './test-launcher-session.mjs';
import { testSuiteFiles } from './trusted-disposable-test-launcher.mjs';

const scope = process.argv[2];
const expected = { family: 3, privacy: 4, 'discovery-sos': 10 }[scope];
assert.ok(expected, 'closed probe scope required');
let connections = 0,
  processes = 0,
  calls = 0,
  failures = 0;
const unexpected = [];
net.Socket.prototype.connect = tls.connect = () => {
  connections++;
  throw new Error('DENIED_NETWORK');
};
child.execFileSync =
  child.spawn =
  child.exec =
  child.execFile =
    () => {
      processes++;
      throw new Error('DENIED_PROCESS');
    };
syncBuiltinESMExports();
// Resolve the existing source exports in this dependency-unlinked worktree.
// Nothing is downloaded, installed or generated by this probe.
const repository = fileURLToPath(new URL('../', import.meta.url));
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (!specifier.startsWith('@shifaa/')) return nextResolve(specifier, context);
    const [, name, ...subpath] = specifier.split('/');
    const folder = ['worker', 'api'].includes(name) ? 'services' : 'packages';
    const directory = path.join(repository, folder, name);
    const manifest = JSON.parse(readFileSync(path.join(directory, 'package.json'), 'utf8'));
    const target = manifest.exports[subpath.length ? './' + subpath.join('/') : '.'];
    assert.equal(typeof target, 'string', 'actual workspace export required');
    return nextResolve(pathToFileURL(path.resolve(directory, target)).href, context);
  },
});
await withTestLauncherSession(
  scope,
  async () => {
    calls++;
    throw new Error('EXPECTED_PROVIDER_PROBE');
  },
  async () => {
    for await (const event of run({
      files: testSuiteFiles(scope),
      isolation: 'none',
      concurrency: 1,
    })) {
      if (event.type !== 'test:fail') continue;
      failures++;
      const error = event.data.details.error;
      if (!/EXPECTED_PROVIDER_PROBE/.test(error.cause?.message ?? error.message))
        unexpected.push(error.cause?.message ?? error.message);
    }
  },
);
process.stdout.write(
  JSON.stringify({ scope, calls, expectedDenials: failures, connections, processes, unexpected }) +
    '\n',
);
assert.deepEqual(unexpected, []);
assert.deepEqual(
  { calls, failures, connections, processes },
  {
    calls: expected,
    failures: expected,
    connections: 0,
    processes: 0,
  },
);
console.log(JSON.stringify({ scope, calls, expectedDenials: failures, connections, processes }));
