type PrefixedKeys<T extends Record<string, string>, Prefix extends string> = {
  [Key in keyof T as `${Prefix}${Capitalize<Key & string>}`]: T[Key];
};

function withPrefix<T extends Record<string, string>, Prefix extends string>(
  value: T,
  prefix: Prefix,
): PrefixedKeys<T, Prefix> {
  return Object.fromEntries(
    Object.entries(value).map(([key, entry]) => [
      `${prefix}${key.charAt(0).toUpperCase()}${key.slice(1)}`,
      entry,
    ]),
  ) as PrefixedKeys<T, Prefix>;
}

