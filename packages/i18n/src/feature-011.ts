export function allergyDate(value: string, locale: 'ar-EG' | 'en-EG'): string {
  const time = Date.parse(value);
  return Number.isFinite(time)
    ? new Intl.DateTimeFormat(`${locale}-u-ca-gregory`, {
        timeZone: 'Africa/Cairo',
        dateStyle: 'medium',
        timeStyle: 'short',
      }).format(time)
    : '—';
}
